<?php

declare(strict_types=1);

namespace Tclp\WpMarkdownForAgents\Tests\Unit\Negotiate;

use PHPUnit\Framework\TestCase;
use Tclp\WpMarkdownForAgents\Core\Options;
use Tclp\WpMarkdownForAgents\Negotiate\AgentDetector;

/**
 * Golden test: pins what AgentDetector answers today for every UA in the corpus.
 *
 * The answers are recorded in tests/fixtures/ua-golden.json, with default options
 * and no filters. The shared agent-signals library must reproduce them, apart from
 * the exceptions named in its spec (SPEC §7.5), so a change here is a change to
 * what that library has to match.
 *
 * To re-record after a deliberate change to the detector or the corpus:
 *
 *     MFA_UPDATE_GOLDEN=1 vendor/bin/phpunit tests/Unit/Negotiate/AgentDetectorGoldenTest.php
 *
 * then review the diff of ua-golden.json before committing it.
 *
 * @covers \Tclp\WpMarkdownForAgents\Negotiate\AgentDetector
 */
class AgentDetectorGoldenTest extends TestCase {

    private const CORPUS = __DIR__ . '/../../fixtures/ua-corpus.json';
    private const GOLDEN = __DIR__ . '/../../fixtures/ua-golden.json';

    /** @var array<string, array<string, mixed>>|null */
    private static ?array $golden = null;

    protected function setUp(): void {
        reset_mock_hooks();
        unset( $GLOBALS['_mock_apply_filters'] );
    }

    /** @return list<array{id: string, ua: string}> */
    private static function corpus(): array {
        $data = json_decode( (string) file_get_contents( self::CORPUS ), true, 512, JSON_THROW_ON_ERROR );

        return $data['cases'];
    }

    /** @return array<string, mixed> What the detector answers for one UA. */
    private static function record( string $ua ): array {
        $detector = new AgentDetector( Options::get_defaults() );
        $detected = $detector->detect_agent( $ua );
        $label    = $detected ?? $detector->normalise_ua( $ua ); // What Negotiator stores in the stats table.

        return array(
            'ua'               => $ua,
            'detect_agent'     => $detected,
            'normalise_ua'     => $detector->normalise_ua( $ua ),
            'label'            => $label,
            'categorise_ua'    => $detector->categorise_agent( $ua ),
            'categorise_label' => $detector->categorise_agent( $label ),
            'operator_ua'      => $detector->get_operator( $ua ),
            'operator_label'   => $detector->get_operator( $label ),
        );
    }

    /** @return array<string, array<string, mixed>> */
    private static function golden(): array {
        if ( null !== self::$golden ) {
            return self::$golden;
        }

        if ( getenv( 'MFA_UPDATE_GOLDEN' ) ) {
            $results = array();
            foreach ( self::corpus() as $case ) {
                $results[ $case['id'] ] = self::record( $case['ua'] );
            }
            $doc = array(
                '_comment' => 'Generated by AgentDetectorGoldenTest from ua-corpus.json with default options and no filters. label is detect_agent ?? normalise_ua, the value Negotiator stores. Do not edit by hand; re-run with MFA_UPDATE_GOLDEN=1.',
                'results'  => $results,
            );
            file_put_contents(
                self::GOLDEN,
                json_encode( $doc, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR ) . "\n"
            );
        }

        $data         = json_decode( (string) file_get_contents( self::GOLDEN ), true, 512, JSON_THROW_ON_ERROR );
        self::$golden = $data['results'];

        return self::$golden;
    }

    /** @return iterable<string, array{string, string}> */
    public function corpus_provider(): iterable {
        foreach ( self::corpus() as $case ) {
            yield $case['id'] => array( $case['id'], $case['ua'] );
        }
    }

    /** @dataProvider corpus_provider */
    public function test_detector_matches_golden_answer( string $id, string $ua ): void {
        $golden = self::golden();

        $this->assertArrayHasKey( $id, $golden, "No golden answer for '$id'. Re-record with MFA_UPDATE_GOLDEN=1." );
        $this->assertSame( $golden[ $id ], self::record( $ua ) );
    }

    public function test_golden_file_covers_exactly_the_corpus(): void {
        $corpus_ids = array_column( self::corpus(), 'id' );

        $this->assertSame( count( $corpus_ids ), count( array_unique( $corpus_ids ) ), 'Corpus ids must be unique.' );
        $this->assertSame( $corpus_ids, array_keys( self::golden() ) );
    }

    public function test_corpus_holds_one_case_per_listed_token(): void {
        $detector = new AgentDetector( Options::get_defaults() );
        $method   = new \ReflectionMethod( $detector, 'get_agent_categories' );
        $tokens   = array_merge( Options::get_defaults()['ua_agent_strings'], ...array_values( $method->invoke( $detector ) ) );
        $uas      = array_column( self::corpus(), 'ua' );

        foreach ( $tokens as $token ) {
            $needle = rtrim( (string) $token, '/' );
            $hits   = array_filter( $uas, static fn( string $ua ): bool => false !== stripos( $ua, $needle ) );
            $this->assertNotEmpty( $hits, "Corpus has no UA holding listed token '$token'." );
        }
    }
}
